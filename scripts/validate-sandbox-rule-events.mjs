import assert from 'node:assert/strict';
import * as THREE from 'three';
import { SandboxMode } from '../src/sandbox/SandboxMode.js';
import * as R from '../src/sandbox/SandboxRules.js';

const events = [];
const mode = new SandboxMode(new THREE.Scene(), { onRuleEvent: event => events.push(event) });
mode.sim.zombies.clear();
mode._insideGate.clear();
mode.sim.spawnZombie({ x: R.SANDBOX_GATE_X, z: R.SANDBOX_GATE_Z, speed: 0 });
mode.sim.spawnZombie({ x: R.SANDBOX_GATE_X + 1, z: R.SANDBOX_GATE_Z, speed: 0 });
mode._emitZoneEvent(6);
mode._emitZoneEvent(12);
assert.equal(events.length, 1);
mode._emitZoneEvent(6 + R.SANDBOX_RULE_EVENT_COOLDOWN_TICKS);
assert.equal(events.length, 1);
mode.sim.zombies.clear();
mode._emitZoneEvent(6 + R.SANDBOX_RULE_EVENT_COOLDOWN_TICKS);
mode.sim.spawnZombie({ x: R.SANDBOX_GATE_X, z: R.SANDBOX_GATE_Z, speed: 0 });
mode._emitZoneEvent(12 + R.SANDBOX_RULE_EVENT_COOLDOWN_TICKS);
assert.equal(events.length, 2);
assert.equal(events[0].zoneId, 'gate');
assert.equal(events[0].entries.length, 2);
assert.ok(events[0].eventId);
mode.sim.zombies.clear();
mode._insidePlayer.clear();
mode._nextRuleEventTick = 0;
mode.sim.player.x = 0;
mode.sim.player.z = 0;
mode.sim.spawnZombie({ x: 1, z: 0, speed: 0 });
mode._emitZoneEvent(200);
assert.equal(events.at(-1).zoneId, 'player');
console.log('PASS: gate entry emits once, then waits for cooldown.');
